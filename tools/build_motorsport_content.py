"""Generate the Motorsport desktop cases and shared mobile data."""
from pathlib import Path
import argparse
import html
import json
import re
from media_collage import collage_figure, presentation_attributes
ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / 'assets/data/motorsport-projects.json').read_text())
E = html.escape


def figure(m, feature=False):
    if m['type'] == 'collage':
        return collage_figure(m, 'ms')
    caption = E(m['caption'])
    if m['type'] == 'video':
        stage = (f'<video controls muted playsinline preload="none" poster="{E(m["poster"])}" '
                 f'aria-label="{caption}"><source src="{E(m["src"])}" type="video/mp4"></video>')
        classes = 'ms-figure ms-video-figure'
    else:
        stage = (f'<img loading="lazy" decoding="async" src="{E(m["src"])}" '
                 f'srcset="{E(m["small"])} {m["smallWidth"]}w, {E(m["src"])} {m["width"]}w" '
                 f'sizes="(max-width: 1000px) 92vw, {"46vw" if feature else "24vw"}" alt="{caption}"{presentation_attributes(m)} />')
        stage = f'<a class="ms-image-link" href="{E(m["src"])}" target="_blank" rel="noopener" aria-label="Open full image: {caption}">{stage}</a>'
        classes = 'media-card ms-figure'
    return f'<figure class="{classes}"><div class="ms-media-stage">{stage}</div><figcaption class="ms-caption">{caption}</figcaption></figure>'


def block(b):
    content = '<ul>'+''.join(f'<li>{E(t)}</li>' for t in b['items'])+'</ul>' if 'items' in b else f'<p>{E(b["text"])}</p>'
    return f'<div class="ms-story-block"><h3>{E(b["label"])}</h3>{content}</div>'


def case(p):
    analysis = ''
    if p.get('analysis'):
        analysis = ('<section class="ms-analysis-section" aria-label="Design and analysis">'
                    '<h3 class="ms-analysis-heading">Design &amp; analysis</h3>'
                    '<div class="ms-analysis-grid">' + ''.join(figure(m) for m in p['analysis']) + '</div></section>')
    return f'''    <section class="section ms-study mode-section" data-mode-section="motorsport" id="{p['id']}" aria-labelledby="{p['id']}-title">
      <div class="ms-case-row">
        <div class="ms-story-copy"><p class="eyebrow">{E(p['eyebrow'])}</p><h2 id="{p['id']}-title">{E(p['title'])}</h2><p class="ms-stage">{E(p['stage'])}</p>{''.join(block(b) for b in p['story'])}</div>
        <div class="ms-feature">{figure(p['feature'], True)}</div>
      </div>
      {analysis}
      <div class="ms-support-grid count-{len(p['support'])}" aria-label="{E(p['shortTitle'])} supporting evidence">{''.join(figure(m) for m in p['support'])}</div>
    </section>
'''


def overview():
    cards=[]
    for p in DATA['projects']:
        m=p['feature']
        cards.append(f'''        <a class="project-card home-project-link visual-project-card" href="#{p['id']}"><div class="project-cover project-cover-contain"><img loading="lazy" src="{E(m['small'])}" alt="{E(m['caption'])}"{presentation_attributes(m)} /></div><div class="project-card-copy"><div class="project-index">{E(p['eyebrow'].split(' · ')[0])} · {E(p['eyebrow'].split(' · ')[1])}</div><h3>{E(p['shortTitle'])}</h3><ul class="project-highlights">{''.join(f"<li>{E(item)}</li>" for item in p["highlights"])}</ul></div></a>''')
    return '''    <section class="section home-showcase mode-section" data-mode-section="motorsport" id="motorsport-projects">
      <div class="section-heading split-heading"><div><p class="eyebrow">Motorsport / Vehicle Systems Engineering</p><h2>Personal Projects</h2></div><a class="text-link" href="#c7-aero">Explore selected case studies ↓</a></div>
      <div class="project-grid visual-project-grid motorsport-project-grid">
'''+'\n'.join(cards)+'''
      </div>
    </section>'''


def outputs():
    index=(ROOT/'index.html').read_text()
    index=re.sub(r'[ \t]*<section class="section home-showcase mode-section" data-mode-section="motorsport" id="motorsport-projects">.*?</section>',overview(),index,count=1,flags=re.S)
    stories='\n'.join(case(p) for p in DATA['projects'])
    stories=re.sub(r'(?m)^[ \t]+$', '', stories)
    stories+='''    <section class="ms-next-step mode-section" data-mode-section="motorsport" aria-label="Continue the conversation about vehicle engineering"><div><p class="eyebrow">Continue the conversation</p><h2>Connect this work to your engineering team.</h2></div><div class="ms-next-actions"><a class="button primary" href="contact.html?mode=motorsport#resumes">View Motorsport resume</a><a class="button secondary" href="contact.html?mode=motorsport">Get in touch</a></div></section>
'''
    generated='    <!-- MOTORSPORT STORIES START: generated by tools/build_motorsport_content.py -->\n'+stories+'    <!-- MOTORSPORT STORIES END -->\n'
    if '<!-- MOTORSPORT STORIES START:' in index:
        index=re.sub(r'    <!-- MOTORSPORT STORIES START:.*?    <!-- MOTORSPORT STORIES END -->\n',lambda _:generated,index,count=1,flags=re.S)
    else:
        start=index.index('    <section class="section case-study mode-section" data-mode-section="motorsport" id="c7-aero">')
        end=index.index('    <section class="section track-video-section',start)
        index=index[:start]+generated+'\n'+index[end:]
    if 'assets/js/motorsport-content.js' not in index:
        index=index.replace('  <script defer src="assets/js/chp-content.js', '  <link rel="stylesheet" href="assets/css/motorsport-stories.css?v=1" />\n  <script defer src="assets/js/motorsport-content.js?v=1"></script>\n  <script defer src="assets/js/chp-content.js',1)
    shared=('/* Generated from assets/data/motorsport-projects.json; run tools/build_motorsport_content.py. */\nwindow.MS_CONTENT = '+json.dumps(DATA,indent=2,ensure_ascii=False)+';\n'
            'window.MS_MEDIA = Object.fromEntries([...window.MS_CONTENT.projects.flatMap(p => [p.feature, ...p.support, ...(p.analysis || [])]), ...window.MS_CONTENT.archiveExtra].flatMap(m => m.panels || [m]).flatMap(m => [[m.src, m], ...(m.small ? [[m.small, m]] : [])]));\n')
    return {'index.html':index,'assets/js/motorsport-content.js':shared}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for file,content in outputs().items():
        target=ROOT/file
        if args.check:
            if not target.exists() or target.read_text()!=content:raise SystemExit(f'Generated content is stale: {file}')
        else:target.write_text(content)
    print('Motorsport desktop content and shared mobile data are current.' if args.check else 'Built Motorsport content.')
